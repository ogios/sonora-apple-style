use std::collections::HashMap;
use std::path::PathBuf;

use crate::{DeviceRule, RuleDevice};
use anyhow::{Context as _, Result, bail};
use gpui::{App, Entity};
use music::equalizer::{Curve, Tone};
use music::scrobble::Account;
use music::{Quality, Transcode, WritingSystem};
use protocol::Call;
use serde_json::Value;
use ui::{Layout, Mode, Pace, Pin, Rounding, Saver, Sorting, Stillness, ThemeKind};

use super::Arguments;
use crate::settings::Frame;
use crate::{
    AppSettings, ConnectName, DiscordName, FilterValue, FullscreenControlsAutohide, PinSort,
    PlayerBarLayout, Repeat, Resume, SideTab,
};

/// Applies preference edits to the server's single persistent settings owner.
pub(super) fn dispatch(call: &Call, entity: &Entity<AppSettings>, cx: &mut App) -> Result<Value> {
    commands!(call, entity, cx, {
                set_equalizer(on: bool => on),
                set_equalizer_advanced(advanced: bool => advanced),
                set_equalizer_tone(tone: Tone => tone),
                select_equalizer_profile(index: usize => index),
                select_equalizer_scratch(curve: Curve => &curve),
                add_equalizer_profile(name: String => &name, curve: Curve => &curve),
                rename_equalizer_profile(index: usize => index, from: String => &from, name: String => &name),
                remove_equalizer_profile(index: usize => index, name: String => &name),
                set_equalizer_rule(rule: DeviceRule => rule),
                remove_equalizer_rule(device: RuleDevice => &device),
                set_equalizer_curve(curve: Curve => &curve),
        place_lyrics_provider(provider: String => &provider, gap: usize => gap),
        set_local_folders(folders: Vec<PathBuf> => folders),
        set_volume(volume: f32 => volume),
        set_normalisation(normalisation: bool => normalisation),
        set_gapless(gapless: bool => gapless),
        set_keep_tracks(keep_tracks: bool => keep_tracks),
        set_offline_mode(offline_mode: bool => offline_mode),
        set_cache_gb(cache_gb: u32 => cache_gb),
        set_spotify_connect(enabled: bool => enabled),
        set_spotify_connect_name(name: ConnectName => name),
        set_spotify_connect_custom_name(name: String => name),
        set_discord_presence(enabled: bool => enabled),
        set_discord_name(name: DiscordName => name),
        set_fullscreen_controls_autohide(fca: FullscreenControlsAutohide => fca),
        set_discord_show_paused(enabled: bool => enabled),
        set_discord_badge(enabled: bool => enabled),
        set_discord_hide_on_connect(enabled: bool => enabled),
        set_discord_without_details(enabled: bool => enabled),
        set_discord_sonora_button(enabled: bool => enabled),
        set_discord_provider_button(enabled: bool => enabled),
        set_artwork_for_local_files(enabled: bool => enabled),
        set_lyrics_for_local_files(enabled: bool => enabled),
        set_output_device(id: Option<String> => id),
        set_output_rate(rate: Option<u32> => rate),
        set_output_buffer(frames: Option<u32> => frames),
        set_transcode(transcode: Transcode => transcode),
        set_quality(quality: Quality => quality),
        set_lyrics_provider(provider: String => &provider, enabled: bool => enabled),
        set_karaoke_lyrics(karaoke: bool => karaoke),
        set_blur_lyrics(blur: bool => blur),
        set_romanized_lyrics(romanized: bool => romanized),
        set_panel_lyrics_scale(scale: f32 => scale),
        set_fullscreen_lyrics_scale(scale: f32 => scale),
        set_romanization_script(writing_system: WritingSystem => writing_system, enabled: bool => enabled),
        set_adaptive_menu(adaptive_menu: bool => adaptive_menu),
        set_check_updates(check_updates: bool => check_updates),
        set_close_to_tray(close_to_tray: bool => close_to_tray),
        set_tray_icon(tray_icon: bool => tray_icon),
        set_stay_awake(stay_awake: bool => stay_awake),
        set_account(service: String => &service, account: Account => account),
        set_scrobbling(service: String => &service, enabled: bool => enabled),
        set_table(table: String => &table, layout: Layout => layout),
        set_view(table: String => &table, mode: Mode => mode),
        set_sorting(table: String => &table, sorting: Option<Sorting> => sorting),
        set_filters(table: String => &table, filters: HashMap<String, FilterValue> => filters),
        set_resume(resume: Option<Resume> => resume),
        set_resume_position(position: f32 => position),
        pin(slug: String => &slug, pin: Pin => pin, gap: Option<usize> => gap, slugs: Vec<String> => &slugs.iter().map(String::as_str).collect::<Vec<_>>()),
        unpin(slug: String => &slug, pin: Pin => &pin),
        set_sidebar(width: f32 => width, open: bool => open),
        set_sidebar_right_width(width: f32 => width),
        set_sidebar_right_open(open: bool => open),
        set_sidebar_right_tab(tab: SideTab => tab),
        remember_search(query: String => &query),
        forget_search(query: String => &query),
        clear_search_history(),
        set_fullscreen_tab(tab: Option<SideTab> => tab),
        set_shuffle(shuffle: bool => shuffle),
        set_repeat(repeat: Repeat => repeat),
        set_radio(radio: bool => radio),
        set_language(language: String => language),
        set_font(font: String => font),
        set_sidebar_pinned_open(open: bool => open),
        set_sidebar_library_open(open: bool => open),
        set_sidebar_full_library(full: bool => full),
        set_sidebar_pin_sort(sort: Option<PinSort> => sort, reversed: bool => reversed),
        rearrange(order: Vec<Pin> => &order, slugs: Vec<String> => &slugs.iter().map(String::as_str).collect::<Vec<_>>()),
        set_nav_shown(entry: String => &entry, shown: bool => shown),
        silence_requirement(slug: String => &slug),
        set_startup(screen: String => screen),
        set_provider(provider: String => provider),
        set_theme(theme: String => theme),
        set_theme_family(family: String => &family),
        set_adaptive_theme(adaptive: bool => adaptive),
        set_ambient(ambient: bool => ambient),
        set_player_bar_layout(layout: PlayerBarLayout => layout),
        set_player_bar_transparent(transparent: bool => transparent),
        set_ambient_motion(motion: bool => motion),
        set_visualizer_style(style: ui::VisualizerStyle => style),
        set_visualizer_absolute(absolute: bool => absolute),
        set_icons(pack: String => pack),
        set_rounding(rounding: String => rounding),
        set_blur(blur: bool => blur),
        set_blur_window(blur: bool => blur),
        set_liquid_glass(liquid: bool => liquid),
        set_os_fullscreen(value: bool => value),
        set_stillness(stillness: Stillness => stillness),
        set_pace(pace: Pace => pace),
        set_system_theme(kind: ThemeKind => kind),
        set_saver(saver: Saver => saver),
        set_server_side_decorations(shown: bool => shown),
        set_window_rounding(rounding: Rounding => rounding),
        set_window_controls(shown: bool => shown),
        set_traffic_light_controls(traffic_light: bool => traffic_light),
        set_controls_on_left(left: bool => left),
        set_font_size(size: f32 => size),
        reset_font_size(),
        set_transparent(transparent: bool => transparent),
        set_transparency(transparency: f32 => transparency),
        set_frame(frame: Frame => frame),
    })
}
